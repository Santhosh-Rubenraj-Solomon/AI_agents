/**
 * services/reviewerService.ts — External `review` CLI runner.
 *
 * Runs the `review` CLI tool in a worktree directory (BEFORE committing).
 * Uses --ci mode with --title, --problem, --solution flags to skip
 * interactive prompts entirely (no TTY/raw-mode required).
 *
 * After completion, parses stdout to find the generated .md file path,
 * reads its content, and returns the review feedback as raw markdown.
 */

import { spawn } from "node:child_process";
import fs from "node:fs/promises";
import { createLogger } from "../utils/logger.js";

const log = createLogger("ReviewCLI");

const REVIEW_CLI_TIMEOUT = 15 * 60 * 1000; // 15 minutes

// ─── Types ───────────────────────────────────────────────────────────────────

export interface ReviewContext {
  /** Task title — passed via --title flag */
  title: string;
  /** Problem description — passed via --problem flag */
  problem: string;
  /** Proposed solution — passed via --solution flag */
  solution: string;
}

export interface ReviewCliResult {
  /** Path to the .md file generated by the review CLI. */
  mdPath: string;
  /** Raw markdown content of the review file. */
  content: string;
  /** Raw stdout from the review CLI command. */
  rawOutput: string;
  /** Whether the review found issues that need fixing. */
  hasIssues: boolean;
}

// ─── .md path extraction ─────────────────────────────────────────────────────

/**
 * Extract a .md file path from the review CLI stdout.
 * Looks for absolute or relative paths ending in .md.
 */
function extractMdPath(stdout: string): string | null {
  const lines = stdout.split("\n");
  // Search from the end — the .md path is usually near the end of output
  for (let i = lines.length - 1; i >= 0; i--) {
    const line = lines[i];
    // Match absolute paths ending in .md
    const absMatch = line.match(/(\/[\w./_-]+\.md)/);
    if (absMatch) return absMatch[1];
    // Match relative paths
    const relMatch = line.match(/(\.{0,2}\/[\w./_-]+\.md)/);
    if (relMatch) return relMatch[1];
  }
  return null;
}

/**
 * Determine whether the review content indicates issues that need fixing.
 */
function detectIssues(content: string): boolean {
  const trimmed = content.trim();

  if (!trimmed || trimmed.length < 20) return false;

  const cleanPatterns = [
    /no\s+issues?\s+found/i,
    /looks\s+good/i,
    /lgtm/i,
    /no\s+changes?\s+(needed|required|necessary)/i,
    /approved?\s*(with\s+no|without)\s+(issues?|comments?|changes?)/i,
    /clean\s+review/i,
    /nothing\s+to\s+(fix|change|report)/i,
    /no\s+changes?\s+found\s+to\s+review/i,
  ];

  for (const pattern of cleanPatterns) {
    if (pattern.test(trimmed)) return false;
  }

  return true;
}

// ─── Main runner ─────────────────────────────────────────────────────────────

/**
 * Run the external `review` CLI in a worktree directory.
 *
 * Uses --ci mode for headless operation (no interactive UI / no TTY required).
 * Context is passed via CLI flags: --title, --problem, --solution.
 *
 * The review CLI's --ci flag disables Ink's interactive rendering, so it works
 * when spawned as a subprocess with piped stdio (no raw mode needed).
 *
 * @param worktreePath - Absolute path to the git worktree directory
 * @param context - Task context (title, problem, solution) for the review
 * @param options - Optional flags to customize review behavior
 * @returns ReviewCliResult with the review content and metadata
 * @throws Error if the CLI fails, times out, or no .md file is found
 */
export async function runReview(
  worktreePath: string,
  context: ReviewContext,
  options?: {
    /** Force a fresh review, ignoring cached checkpoints. Default: true */
    fresh?: boolean;
    /** Review source type. Default: "local" (uncommitted changes) */
    source?: string;
  },
): Promise<ReviewCliResult> {
  const { fresh = true, source = "local" } = options ?? {};

  // Build CLI arguments — all context via flags, no interactive prompts
  const args: string[] = [
    "--ci",
    "--source", source,
    "--title", context.title,
    "--problem", context.problem,
    "--solution", context.solution,
  ];

  if (fresh) {
    args.push("--fresh");
  }

  log.info("Running review CLI in --ci mode", {
    cwd: worktreePath,
    args: args.join(" "),
  });
  log.info("Review context", {
    title: context.title,
    problem: context.problem.slice(0, 100),
    solution: context.solution.slice(0, 100),
  });

  const startTime = Date.now();

  return new Promise<ReviewCliResult>((resolve, reject) => {
    const proc = spawn("review", args, {
      cwd: worktreePath,
      env: { ...process.env },
      stdio: ["ignore", "pipe", "pipe"],
    });

    let stdout = "";
    let stderr = "";
    let timeoutHandle: NodeJS.Timeout;

    // Set timeout
    timeoutHandle = setTimeout(() => {
      log.error("Review CLI timed out", { elapsedMs: REVIEW_CLI_TIMEOUT });
      proc.kill("SIGTERM");
      setTimeout(() => proc.kill("SIGKILL"), 5000);
      reject(new Error(`Review CLI timed out after ${REVIEW_CLI_TIMEOUT / 1000}s`));
    }, REVIEW_CLI_TIMEOUT);

    // Stream stdout in real-time
    proc.stdout.on("data", (chunk: Buffer) => {
      const text = chunk.toString();
      stdout += text;

      // Log each line in real-time
      for (const line of text.split("\n")) {
        if (line.trim()) {
          log.info(`[stdout] ${line.trim()}`);
        }
      }
    });

    // Stream stderr in real-time
    proc.stderr.on("data", (chunk: Buffer) => {
      const text = chunk.toString();
      stderr += text;

      for (const line of text.split("\n")) {
        if (line.trim()) {
          log.warn(`[stderr] ${line.trim()}`);
        }
      }
    });

    proc.on("close", async (code) => {
      clearTimeout(timeoutHandle);
      const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
      log.info("Review CLI exited", { code, elapsedSec: elapsed, stdoutLength: stdout.length });

      // Non-zero exit is OK if we got output (some CLIs exit non-zero when issues found)
      if (code !== 0 && !stdout.trim()) {
        reject(new Error(
          `Review CLI exited with code ${code} and no output. Stderr: ${stderr.slice(0, 500)}`
        ));
        return;
      }

      // Extract the .md file path from stdout
      const mdPath = extractMdPath(stdout);
      if (!mdPath) {
        // Check if "No changes found to review" — this means the diff was empty
        if (/no\s+changes?\s+found/i.test(stdout)) {
          log.info("Review CLI found no changes to review");
          resolve({
            mdPath: "",
            content: "No changes found to review.",
            rawOutput: stdout,
            hasIssues: false,
          });
          return;
        }

        reject(new Error(
          `Could not find a .md file path in review CLI output.\nstdout:\n${stdout.slice(0, 2000)}`
        ));
        return;
      }

      log.info("Found review .md file", { mdPath });

      // Read the review markdown file
      let content: string;
      try {
        content = await fs.readFile(mdPath, "utf-8");
      } catch (readErr: unknown) {
        reject(new Error(
          `Review CLI referenced "${mdPath}" but file could not be read: ${(readErr as Error).message}`
        ));
        return;
      }

      const hasIssues = detectIssues(content);

      log.info("Review parsed", { mdPath, contentLength: content.length, hasIssues });

      resolve({
        mdPath,
        content,
        rawOutput: stdout,
        hasIssues,
      });
    });

    proc.on("error", (err) => {
      clearTimeout(timeoutHandle);
      reject(new Error(`Failed to spawn review CLI: ${err.message}`));
    });
  });
}
