// ─── Claude JSON parsing utility ──────────────────────────────────────────────

/**
 * Custom error for Claude output parse failures.
 */
export class ClaudeParseError extends Error {
  constructor(
    message: string,
    public readonly rawOutput: string,
    public readonly cause?: unknown
  ) {
    super(message);
    this.name = "ClaudeParseError";
  }
}

/**
 * Parses raw Claude CLI output into a Zod-validated typed result.
 *
 * Steps:
 * 1. Strip markdown code fences
 * 2. JSON.parse
 * 3. If parse fails, regex-extract outermost {...}
 * 4. Zod validate
 * 5. Throw descriptive ClaudeParseError on failure
 */
export function parseClaudeJson<T>(raw: string, schema: z.ZodSchema<T>): T {
  // Step 1: Strip code fences
  let cleaned = raw.replace(/```(?:json)?\s*\n?/g, "").trim();

  // Step 2: Try direct JSON.parse
  let parsed: unknown;
  try {
    parsed = JSON.parse(cleaned);
  } catch {
    // Step 3: Regex extract outermost { ... }
    const match = cleaned.match(/\{[\s\S]*\}/);
    if (!match) {
      throw new ClaudeParseError(
        "Could not extract JSON object from Claude output",
        raw
      );
    }
    try {
      parsed = JSON.parse(match[0]);
    } catch (innerErr) {
      throw new ClaudeParseError(
        "Extracted JSON block is not valid JSON",
        raw,
        innerErr
      );
    }
  }

  // Step 4: Zod validate
  const result = schema.safeParse(parsed);
  if (!result.success) {
    const issues = result.error.issues
      .map((i) => `  ${i.path.join(".")}: ${i.message}`)
      .join("\n");
    throw new ClaudeParseError(
      `Claude output failed schema validation:\n${issues}`,
      raw,
      result.error
    );
  }

  return result.data;
}

