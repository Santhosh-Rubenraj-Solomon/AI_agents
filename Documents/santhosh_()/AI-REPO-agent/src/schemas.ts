// ─── Conventional commit helpers ──────────────────────────────────────────────

/**
 * Map task type to conventional commit type prefix.
 * Reuses TYPE_PREFIX_MAP (already defined above for branch names).
 */
const COMMIT_TYPE_MAP: Record<TaskType, string> = TYPE_PREFIX_MAP;

/**
 * Build a conventional commit message from task metadata.
 *
 * Format: `<type>(<scope>): <description>`
 *
 * - type:        mapped from TaskType (bugfix -> fix, feature -> feat, etc.)
 * - scope:       the service name (e.g. "electronic-cash-register")
 * - description: the task title, first letter lowercased, truncated to
 *                keep the full message under 100 characters (with ellipsis).
 */
export function buildConventionalCommitMessage(
  type: TaskType,
  serviceName: string,
  title: string,
): string {
  const commitType = COMMIT_TYPE_MAP[type] ?? type;

  // Lowercase the first character of the description
  const desc = title.charAt(0).toLowerCase() + title.slice(1);

  // The prefix is "<type>(<scope>): " — calculate its length to know how
  // much room is left for the description within the 100-char limit.
  const prefix = `${commitType}(${serviceName}): `;
  const maxDescLen = 100 - prefix.length;

  const truncatedDesc =
    desc.length > maxDescLen
      ? desc.slice(0, maxDescLen - 3) + "..."
      : desc;

  return `${prefix}${truncatedDesc}`;
}
